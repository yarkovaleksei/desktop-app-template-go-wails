// Package archtest — тесты правил архитектуры шаблона. Кода у пакета нет,
// только тесты.
//
// Правила, которые проверяют тесты:
//   - Wails (и kit/wailsx, который его импортирует) доступен только пакету
//     main и internal/app; ядро в internal/ работает без Wails и без фронтенда;
//   - коды ошибок, которые Go отдаёт фронтенду (константы Code* шаблона и коды
//     update.* из kit), перечислены в frontend/src/i18n/error-codes.json —
//     по этому списку тест словарей фронтенда (Vitest) проверяет тексты на
//     обоих языках; так коды kit сверяются с обоими словарями;
//   - имена из internal/appinfo совпадают с повторёнными вне Go: build/config.yml,
//     Taskfile.yml, frontend/index.html, nfpm, файл .desktop,
//     scripts/smoke-desktop.sh;
//   - у каждого ключа, с которым Go-код вызывает texts.T (трей, уведомления,
//     автозапуск), есть текст на всех языках internal/texts;
//   - README.md и README.en.md состоят из одинаковых разделов, а имена пакетов
//     и файлов сумм в них совпадают с updater.Naming для RELEASE_FORMATS;
//   - сайт www/index.html: наборы текстов en и ru совпадают, английский в
//     разметке равен словарю en; суффиксы вложений в скрипте совпадают с
//     updater.Naming для RELEASE_FORMATS; адреса сайта — Pages репозитория,
//     размеры картинок — как на странице;
//   - у каждого скилла .agents/skills/<имя> есть SKILL.md с name, равным имени
//     каталога, и непустым description, симлинк .claude/skills/<имя> для
//     Claude Code и строка в таблице «Скиллы» AGENTS.md.
//
// Правило, которое тест не проверяет и которое держит обзор кода:
// internal/app не содержит логики, кроме перевода вызовов в ядро, ответов в
// DTO и ошибок в *apperr.Error.
